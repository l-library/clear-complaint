"""九个病种域的受控定义与关键词表。

阶段一的三处逻辑要共用同一份域定义：覆盖率统计、文档域标签、之后的分域指标。
分散在各脚本里会导致「统计里算九个域、标签里算十个域」这种自相矛盾。
"""

from __future__ import annotations

# 关节痛已砍掉：全库只有基孔肯雅热一份文件涉及，补不出材料，留着只会稀释效应量。
DOMAINS: dict[str, tuple[str, ...]] = {
    "发热待查": ("发热", "体温", "高热", "热程", "稽留热"),
    "呼吸道症状": ("咳嗽", "流涕", "咽痛", "鼻塞", "咳痰", "气促", "呼吸困难"),
    "腹泻呕吐": ("腹泻", "呕吐", "水样便", "稀便", "脱水", "补液"),
    "皮疹": ("皮疹", "斑丘疹", "疱疹", "出血点", "结膜充血"),
    "胸痛心悸": ("胸痛", "胸闷", "心悸", "胸骨后", "压榨性", "心绞痛"),
    "头晕与意识改变": ("头晕", "头痛", "意识障碍", "意识改变", "抽搐", "惊厥"),
    "乏力与水肿": ("乏力", "水肿", "贫血", "活动耐量", "气短"),
    "伤口与动物致伤": ("咬伤", "抓伤", "伤口", "暴露后", "狂犬", "破伤风"),
    # 不要用「随访」「转诊」这类流程词：儿童肿瘤的文件都有「转诊条件」章节，
    # 加进去会把一整套肿瘤规范标成慢病随访。只认疾病词。
    "慢病随访": ("血压", "血糖", "血脂", "糖尿病", "高血压", "慢阻肺", "心力衰竭", "脑卒中"),
}

# 一个条款命中同一域至少两个关键词才算提及，压掉偶然共现（单靠「关节」两字
# 就能给一个无关文件打上标签的情况）
MIN_KEYWORD_HITS = 2


def hits(text: str) -> set[str]:
    return {
        name
        for name, words in DOMAINS.items()
        if sum(1 for word in words if word in text) >= MIN_KEYWORD_HITS
    }
