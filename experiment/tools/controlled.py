def triggers_for(rule_id: str, base: tuple[str, ...]) -> tuple[str, ...]:
    """原有触发词加补充表，顺序稳定、去重。"""
    merged = list(base)
    for extra in EXTRA_TRIGGERS.get(rule_id, ()):
        if extra not in merged:
            merged.append(extra)
    return tuple(merged)


