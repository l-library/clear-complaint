"""账号域的 ORM 模型：用户、隐私同意记录、刷新令牌。

表结构只由 Alembic 迁移创建，这里只做映射。命名遵循约定：表名单数、
主键 BIGINT GENERATED BY DEFAULT AS IDENTITY、时间列 TIMESTAMPTZ。
"""

from datetime import date, datetime

from sqlalchemy import (
    BigInteger,
    Boolean,
    Date,
    DateTime,
    ForeignKey,
    Identity,
    String,
    func,
)
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.orm import Mapped, mapped_column

from app.db.base import Base


class User(Base):
    __tablename__ = "user"

    id: Mapped[int] = mapped_column(BigInteger, Identity(), primary_key=True)
    phone: Mapped[str] = mapped_column(String(11), unique=True)
    # pbkdf2_sha256$<迭代>$<盐hex>$<哈希hex>，标准库实现，不引第三方
    password_hash: Mapped[str] = mapped_column(String(255))
    is_demo: Mapped[bool] = mapped_column(Boolean, server_default="false")
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), onupdate=func.now()
    )


class Consent(Base):
    """注册时的隐私同意记录。后续版本过期要重新确认，按版本存行。"""

    __tablename__ = "consent"

    id: Mapped[int] = mapped_column(BigInteger, Identity(), primary_key=True)
    user_id: Mapped[int] = mapped_column(ForeignKey("user.id"), index=True)
    version: Mapped[str] = mapped_column(String(32))
    sensitive_accepted: Mapped[bool] = mapped_column(Boolean)
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), onupdate=func.now()
    )


class RefreshToken(Base):
    """刷新令牌只存哈希。轮换即作废旧令牌，重放按 used_at 判定。"""

    __tablename__ = "refresh_token"

    id: Mapped[int] = mapped_column(BigInteger, Identity(), primary_key=True)
    user_id: Mapped[int] = mapped_column(ForeignKey("user.id"), index=True)
    token_hash: Mapped[str] = mapped_column(String(64), unique=True)
    expires_at: Mapped[datetime] = mapped_column(DateTime(timezone=True))
    used_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True), default=None)
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), onupdate=func.now()
    )


class Profile(Base):
    """健康档案。每人一行，必填项只有 birth_date 与 sex，其余可缺。

    conditions/allergies 用 JSONB 存：null 表示未告知，[] 表示用户明确确认没有
    （docs/api-agentarts.md 16.4：不能把空数组当未知，也不能把 null 当确认无）。
    """

    __tablename__ = "profile"

    id: Mapped[int] = mapped_column(BigInteger, Identity(), primary_key=True)
    user_id: Mapped[int] = mapped_column(ForeignKey("user.id"), unique=True)
    name: Mapped[str | None] = mapped_column(String(40), default=None)
    birth_date: Mapped[date | None] = mapped_column(Date, default=None)
    sex: Mapped[str | None] = mapped_column(String(12), default=None)
    city_code: Mapped[str | None] = mapped_column(String(6), default=None)
    city_name: Mapped[str | None] = mapped_column(String(40), default=None)
    conditions: Mapped[list[str] | None] = mapped_column(JSONB, default=None)
    condition_note: Mapped[str | None] = mapped_column(String(200), default=None)
    allergies: Mapped[list[str] | None] = mapped_column(JSONB, default=None)
    allergy_note: Mapped[str | None] = mapped_column(String(200), default=None)
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), onupdate=func.now()
    )
